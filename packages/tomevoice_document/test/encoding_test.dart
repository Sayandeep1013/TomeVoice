Uint8List _b(List<int> bytes) => Uint8List.fromList(bytes);

/// Text from code points, so no non-ASCII character has to be typed here.
String _cp(List<int> codes) => String.fromCharCodes(codes);

/// "Он пришёл домой" in code points.
final _russianStart = _cp([0x41E, 0x43D, 0x20, 0x43F, 0x440, 0x438, 0x448, 0x451, 0x43B, 0x20, 0x434, 0x43E, 0x43C, 0x43E, 0x439]);

Uint8List _epubWith(List<int> chapter) {
  final a = Archive();
  void add(String name, List<int> data) => a.addFile(ArchiveFile.bytes(name, data));
  a.addFile(ArchiveFile.noCompress('mimetype', 20, utf8.encode('application/epub+zip')));
  add('META-INF/container.xml',
      utf8.encode('<container><rootfiles><rootfile full-path="OEBPS/content.opf"/></rootfiles></container>'));
  add('OEBPS/content.opf', utf8.encode('''
<package xmlns="http://www.idpf.org/2007/opf" version="2.0">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:title>Enc</dc:title><dc:language>fr</dc:language></metadata>
  <manifest><item id="c" href="c.xhtml" media-type="application/xhtml+xml"/></manifest>
  <spine><itemref idref="c"/></spine>
</package>'''));
  add('OEBPS/c.xhtml', chapter);
  return Uint8List.fromList(ZipEncoder().encode(a));
}

void main() {
  group('plain text', () {
    test('mostly UTF-8 with one stray byte stays UTF-8', () {
      final text = decodeText(_b(_bengaliStray));
      expect(text, startsWith(_cp([0x986, 0x9AE, 0x9BF])));
      // The stray 0x97 is read as the windows-1252 em dash it was.
      expect(text, contains(_cp([0x20, 0x2014, 0x20])));
      final book = ingestBytes(_b(_bengaliStray), filename: 'golpo.txt');
      expect(book.metadata.language, 'bn');
    });

    test('Russian in windows-1251, KOI8-R and CP866', () {
      for (final bytes in [_cp1251, _koi8r, _cp866]) {
        expect(decodeText(_b(bytes)), startsWith(_russianStart));
      }
      expect(ingestBytes(_b(_koi8r), filename: 'r.txt').metadata.language, 'ru');
    });

    test('Latin text with a few accents is still windows-1252', () {
      final bytes = _b([...latin1.encode('Caf'), 0xE9, ...latin1.encode(' au lait, d'), 0x92, ...latin1.encode('accord.')]);
      expect(decodeText(bytes), 'Caf${_cp([0xE9])} au lait, d${_cp([0x2019])}accord.');
    });

    test('a page of densely accented French is not taken for Cyrillic or Chinese', () {
      // "Déjà été là, ça s'écrit à côté. Où êtes-vous, Hélène ? Très près."
      final line = _b([
        0x44, 0xE9, 0x6A, 0xE0, 0x20, 0xE9, 0x74, 0xE9, 0x20, 0x6C, 0xE0, 0x2C, 0x20, 0xE7, 0x61, 0x20,
        0x73, 0x27, 0xE9, 0x63, 0x72, 0x69, 0x74, 0x20, 0xE0, 0x20, 0x63, 0xF4, 0x74, 0xE9, 0x2E, 0x20,
        0x4F, 0xF9, 0x20, 0xEA, 0x74, 0x65, 0x73, 0x2D, 0x76, 0x6F, 0x75, 0x73, 0x2C, 0x20, 0x48, 0xE9,
        0x6C, 0xE8, 0x6E, 0x65, 0x20, 0x3F, 0x20, 0x54, 0x72, 0xE8, 0x73, 0x20, 0x70, 0x72, 0xE8, 0x73,
        0x2E, 0x0A,
      ]);
      final bytes = _b([for (var i = 0; i < 40; i++) ...line]);
      final text = decodeText(bytes);
      expect(text, startsWith('D${_cp([0xE9])}j${_cp([0xE0])} ${_cp([0xE9])}t${_cp([0xE9])}'));
    });

    test('byte order marks: UTF-8, UTF-16 and UTF-32', () {
      expect(decodeText(_b([0xEF, 0xBB, 0xBF, 0x48, 0x69])), 'Hi');
      expect(decodeText(_b([0xFE, 0xFF, 0, 0x48, 0, 0x69])), 'Hi');
      expect(decodeText(_b([0xFF, 0xFE, 0, 0, 0x48, 0, 0, 0, 0x69, 0, 0, 0])), 'Hi');
    });

    test('East Asian encodings are recognised and handed to the decoder', () {
      final seen = <String>[];
      String fake(Uint8List bytes, String charset) {
        seen.add(charset);
        return 'decoded as $charset';
      }

      expect(decodeText(_b(_gb18030), legacy: fake), 'decoded as GB18030');
      expect(decodeText(_b(_big5), legacy: fake), 'decoded as Big5');
      expect(decodeText(_b(_shiftJis), legacy: fake), 'decoded as Shift_JIS');
      expect(decodeText(_b(_eucJp), legacy: fake), 'decoded as EUC-JP');
      expect(decodeText(_b(_eucKr), legacy: fake), 'decoded as EUC-KR');
      expect(seen, hasLength(5));
    });

    test('without a decoder they fail clearly instead of becoming gibberish', () {
      expect(
        () => ingestBytes(_b(_gb18030), filename: 'novel.txt'),
        throwsA(isA<LegacyEncodingException>()
            .having((e) => e.charset, 'charset', 'GB18030')
            .having((e) => e.message, 'message', contains('UTF-8'))),
      );
    });

    test('the decoder hook reaches a TXT import', () {
      final book = ingestBytes(
        _b(_gb18030),
        filename: 'novel.txt',
        legacyDecoder: (bytes, charset) => '${_cp([0x5E8A, 0x524D, 0x660E, 0x6708, 0x5149, 0x3002])} $charset',
      );
      expect(book.sections.first.blocks.first.text, contains('GB18030'));
    });

    test('an async decoder (a platform channel) is asked once per text', () async {
      var calls = 0;
      final book = await ingestBytesAsync(
        _b(_shiftJis),
        filename: 'neko.txt',
        decodeLegacy: (bytes, charset) async {
          calls++;
          return '${_cp([0x543E, 0x8F29, 0x306F, 0x732B, 0x3067, 0x3042, 0x308B, 0x3002])} ($charset)';
        },
      );
      expect(calls, 1);
      expect(book.metadata.language, 'ja');
      expect(book.sections.first.blocks.first.text, contains('Shift_JIS'));
    });

    test('labels', () {
      expect(charsetOf('ISO_8859-1'), 'windows-1252');
      expect(charsetOf('cp1251'), 'windows-1251');
      expect(charsetOf('KOI8-R'), 'koi8-r');
      expect(charsetOf('x-sjis'), 'Shift_JIS');
      expect(charsetOf('gb2312'), 'GB18030');
      expect(charsetOf('iso8859-5'), 'iso-8859-5');
      expect(charsetOf('nonsense'), isNull);
    });
  });

  group('markup', () {
    test('EPUB XHTML declared ISO-8859-1 or windows-1252', () {
      for (final enc in ['ISO-8859-1', 'windows-1252']) {
        final chapter = <int>[
          ...latin1.encode('<?xml version="1.0" encoding="$enc"?><html xmlns="http://www.w3.org/1999/xhtml"><body><p>Le caf'),
          0xE9,
          ...latin1.encode(' est pr'),
          0xEA,
          ...latin1.encode('t, n'),
          0x92,
          ...latin1.encode('est-ce pas ? Oui, il est bon et chaud.</p></body></html>'),
        ];
        final book = ingestBytes(_epubWith(chapter), filename: 'cafe.epub');
        final text = book.sections.first.blocks.first.text;
        expect(text, contains('caf${_cp([0xE9])} est pr${_cp([0xEA])}t, n${_cp([0x2019])}est'));
        expect(text, isNot(contains(_cp([0xFFFD]))));
      }
    });

    test('a file that says Latin-1 but is UTF-8 is read as UTF-8', () {
      final chapter = utf8.encode('<?xml version="1.0" encoding="iso-8859-1"?><html><body><p>'
          'Caf${_cp([0xE9])} cr${_cp([0xE8])}me, a long enough sentence.</p></body></html>');
      final book = ingestBytes(_epubWith(chapter), filename: 'liar.epub');
      expect(book.sections.first.blocks.first.text, startsWith('Caf${_cp([0xE9])} cr${_cp([0xE8])}me'));
    });

    test('an HTML file with <meta charset>', () {
      final bytes = _b([
        ...latin1.encode('<html><head><meta charset="windows-1251"></head><body><p>'),
        ..._cp1251,
        ...latin1.encode('</p></body></html>'),
      ]);
      final book = ingestBytes(bytes, filename: 'r.html');
      expect(book.sections.first.blocks.first.text, startsWith(_russianStart));
    });

    test('FB2 in KOI8-R', () {
      final bytes = _b([
        ...latin1.encode('<?xml version="1.0" encoding="koi8-r"?><FictionBook><description><title-info>'
            '<book-title>K</book-title></title-info></description><body><section><p>'),
        ..._koi8r,
        ...latin1.encode('</p></section></body></FictionBook>'),
      ]);
      final book = ingestBytes(bytes, filename: 'k.fb2');
      expect(book.sections.first.blocks.first.text, startsWith(_russianStart));
    });
  });

  group('RTF', () {
    test(r'\ansicpg1251 decodes its bytes as Cyrillic', () {
      final hex = [for (final b in _cp1251.take(15)) "\\'${b.toRadixString(16).padLeft(2, '0')}"].join();
      final rtf = '{\\rtf1\\ansi\\ansicpg1251{\\fonttbl{\\f0 Times;}}\\f0 $hex.\\par}';
      final book = ingestBytes(_b(latin1.encode(rtf)), filename: 'r.rtf');
      expect(book.sections.first.blocks.first.text, '$_russianStart.');
    });

    test(r'a Cyrillic font (\fcharset204) in a Western document', () {
      final hex = [for (final b in _cp1251.take(15)) "\\'${b.toRadixString(16).padLeft(2, '0')}"].join();
      final rtf = '{\\rtf1\\ansi\\ansicpg1252{\\fonttbl{\\f0\\fcharset0 Arial;}{\\f1\\fcharset204 Arial;}}'
          "\\f0 Caf\\'e9 \\f1 $hex.\\par}";
      final book = ingestBytes(_b(latin1.encode(rtf)), filename: 'r.rtf');
      expect(book.sections.first.blocks.first.text, 'Caf${_cp([0xE9])} $_russianStart.');
    });

    test(r'a double-byte code page goes through the decoder', () {
      final hex = [for (final b in _shiftJis.take(10)) "\\'${b.toRadixString(16).padLeft(2, '0')}"].join();
      final rtf = '{\\rtf1\\ansi\\ansicpg932 $hex\\par}';
      final book = ingestBytes(
        _b(latin1.encode(rtf)),
        filename: 'j.rtf',
        legacyDecoder: (bytes, charset) => '[$charset ${bytes.length}]',
      );
      expect(book.sections.first.blocks.first.text, '[Shift_JIS 10]');
      expect(() => ingestBytes(_b(latin1.encode(rtf)), filename: 'j.rtf'), throwsA(isA<LegacyEncodingException>()));
    });
  });
}
